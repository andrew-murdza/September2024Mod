import java.awt.image.BufferedImage;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import javax.imageio.ImageIO;

/**
 * Run from the repository root with: java scripts/GenerateSoulPlantModels.java
 * Splits the original plant textures into textured model faces, without editing images.
 * Forge's native face lightmap makes cyan foliage/fruit fullbright, while brown pixels
 * retain normal world lighting. Rectangles may overlap only where the texture is transparent.
 */
public final class GenerateSoulPlantModels {
    private static final Path ASSETS = Path.of("src/main/resources/assets/aoemod");
    private static final int SIZE = 16;

    public static void main(String[] args) throws IOException {
        for (String plant : List.of("soul_berry_bush", "soul_beetroots")) {
            for (int age = 0; age <= 3; age++) {
                String name = plant + "_stage" + age;
                BufferedImage image = ImageIO.read(ASSETS.resolve("textures/block/" + name + ".png").toFile());
                if (image.getWidth() != SIZE || image.getHeight() != SIZE) {
                    throw new IllegalArgumentException(name + " must be a 16 by 16 texture");
                }
                List<Region> regions = partition(image);
                verify(image, regions);
                boolean crop = plant.equals("soul_beetroots");
                String textureKey = crop ? "crop" : "cross";
                List<String> elements = new ArrayList<>();
                for (Region region : regions) {
                    if (crop) {
                        // Vanilla crop rows, raised one pixel to meet full-height soul blocks.
                        addFace(elements, region, "west", 4, 0, 16, false, false, textureKey);
                        addFace(elements, region, "east", 4, 0, 16, true, false, textureKey);
                        addFace(elements, region, "west", 12, 0, 16, true, false, textureKey);
                        addFace(elements, region, "east", 12, 0, 16, false, false, textureKey);
                        addFace(elements, region, "north", 4, 0, 16, false, false, textureKey);
                        addFace(elements, region, "south", 4, 0, 16, true, false, textureKey);
                        addFace(elements, region, "north", 12, 0, 16, true, false, textureKey);
                        addFace(elements, region, "south", 12, 0, 16, false, false, textureKey);
                    } else {
                        // Keep the dimensions, rotation and UV orientation of minecraft:block/cross.
                        for (String face : List.of("north", "south", "west", "east")) {
                            addFace(elements, region, face, 8, 0.8, 15.2, false, true, textureKey);
                        }
                    }
                }
                String model = "{\n"
                        + "  \"_comment\": \"Generated by scripts/GenerateSoulPlantModels.java; fullbright faces do not emit block light.\",\n"
                        + "  \"ambientocclusion\": false,\n"
                        + "  \"render_type\": \"minecraft:cutout\",\n"
                        + "  \"textures\": {\"particle\": \"#" + textureKey + "\", \"" + textureKey
                        + "\": \"aoemod:block/" + name + "\"},\n"
                        + "  \"elements\": [\n    " + String.join(",\n    ", elements) + "\n  ]\n}\n";
                Files.writeString(ASSETS.resolve("models/block/" + name + ".json"), model, StandardCharsets.UTF_8);
                System.out.println(name + ": " + regions.size() + " texture regions, " + elements.size() + " faces");
            }
        }
    }

    private static boolean emissive(int pixel) {
        int red = (pixel >>> 16) & 255;
        int green = (pixel >>> 8) & 255;
        int blue = pixel & 255;
        // Includes dark cyan, pale cyan and white highlights, excludes brown stems/roots.
        return (green > red * 1.15 && blue > red * 1.15)
                || (red >= 220 && green >= 220 && blue >= 220);
    }

    private static boolean opaque(int pixel) {
        return (pixel >>> 24) != 0;
    }

    private static List<Region> partition(BufferedImage image) {
        boolean[][] covered = new boolean[SIZE][SIZE];
        List<Region> result = new ArrayList<>();
        for (int y = 0; y < SIZE; y++) {
            for (int x = 0; x < SIZE; x++) {
                if (!opaque(image.getRGB(x, y)) || covered[y][x]) {
                    continue;
                }
                boolean glow = emissive(image.getRGB(x, y));
                int[][] forbidden = new int[SIZE + 1][SIZE + 1];
                int[][] wanted = new int[SIZE + 1][SIZE + 1];
                for (int row = 0; row < SIZE; row++) {
                    for (int column = 0; column < SIZE; column++) {
                        int pixel = image.getRGB(column, row);
                        boolean visible = opaque(pixel);
                        boolean valid = !covered[row][column] && emissive(pixel) == glow;
                        addPrefix(forbidden, column, row, visible && !valid ? 1 : 0);
                        addPrefix(wanted, column, row, visible && valid ? 1 : 0);
                    }
                }
                Region best = null;
                int bestCount = 0;
                int bestArea = Integer.MAX_VALUE;
                for (int top = 0; top <= y; top++) {
                    for (int left = 0; left <= x; left++) {
                        for (int bottom = y + 1; bottom <= SIZE; bottom++) {
                            for (int right = x + 1; right <= SIZE; right++) {
                                if (sum(forbidden, left, top, right, bottom) != 0) {
                                    continue;
                                }
                                int count = sum(wanted, left, top, right, bottom);
                                int area = (right - left) * (bottom - top);
                                if (count > bestCount || (count == bestCount && area < bestArea)) {
                                    best = new Region(left, top, right, bottom, glow);
                                    bestCount = count;
                                    bestArea = area;
                                }
                            }
                        }
                    }
                }
                result.add(best);
                for (int row = best.top; row < best.bottom; row++) {
                    for (int column = best.left; column < best.right; column++) {
                        if (opaque(image.getRGB(column, row))) {
                            covered[row][column] = true;
                        }
                    }
                }
            }
        }
        return result;
    }

    private static void addPrefix(int[][] prefix, int x, int y, int value) {
        prefix[y + 1][x + 1] = value + prefix[y][x + 1] + prefix[y + 1][x] - prefix[y][x];
    }

    private static int sum(int[][] prefix, int left, int top, int right, int bottom) {
        return prefix[bottom][right] - prefix[top][right] - prefix[bottom][left] + prefix[top][left];
    }

    private static void verify(BufferedImage image, List<Region> regions) {
        for (int y = 0; y < SIZE; y++) {
            for (int x = 0; x < SIZE; x++) {
                int pixel = image.getRGB(x, y);
                if (!opaque(pixel)) {
                    continue;
                }
                int matches = 0;
                for (Region region : regions) {
                    if (x >= region.left && x < region.right && y >= region.top && y < region.bottom) {
                        if (region.glow != emissive(pixel)) {
                            throw new IllegalStateException("Incorrect lightmap at " + x + ", " + y);
                        }
                        matches++;
                    }
                }
                if (matches != 1) {
                    throw new IllegalStateException("Missing or overlapping geometry at " + x + ", " + y);
                }
            }
        }
    }

    private static void addFace(List<String> elements, Region region, String face, double plane,
                                double minimum, double maximum, boolean reverseUv, boolean cross, String textureKey) {
        boolean reversedFace = face.equals("north") || face.equals("east");
        boolean reversedPosition = reversedFace ^ reverseUv;
        double start = reversedPosition ? SIZE - region.right : region.left;
        double end = reversedPosition ? SIZE - region.left : region.right;
        double from = minimum + (maximum - minimum) * start / SIZE;
        double to = minimum + (maximum - minimum) * end / SIZE;
        double bottom = SIZE - region.bottom;
        double top = SIZE - region.top;
        boolean xPlane = face.equals("west") || face.equals("east");
        String fromVector = xPlane ? vector(plane, bottom, from) : vector(from, bottom, plane);
        String toVector = xPlane ? vector(plane, top, to) : vector(to, top, plane);
        String uv = "[" + (reverseUv ? region.right : region.left) + ", " + region.top + ", "
                + (reverseUv ? region.left : region.right) + ", " + region.bottom + "]";
        elements.add("{\"from\": " + fromVector + ", \"to\": " + toVector
                + (cross ? ", \"rotation\": {\"origin\": [8, 8, 8], \"axis\": \"y\", \"angle\": 45, \"rescale\": true}" : "")
                + ", \"shade\": false"
                + (region.glow ? ", \"forge_data\": {\"block_light\": 15, \"sky_light\": 15, \"ambient_occlusion\": false}" : "")
                + ", \"faces\": {\"" + face + "\": {\"uv\": " + uv + ", \"texture\": \"#" + textureKey + "\"}}}");
    }

    private static String vector(double x, double y, double z) {
        return "[" + number(x) + ", " + number(y) + ", " + number(z) + "]";
    }

    private static String number(double value) {
        return java.math.BigDecimal.valueOf(Math.round(value * 1000) / 1000.0).stripTrailingZeros().toPlainString();
    }

    private record Region(int left, int top, int right, int bottom, boolean glow) { }
}
